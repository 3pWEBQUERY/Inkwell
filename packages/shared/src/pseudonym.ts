export function suggestPseudonym(
  locale: keyof typeof WORDS,
  random: () => number = Math.random,
): string {
  const list = WORDS[locale];
  const adjective = pick(list.adjectives, random);
  const noun = pick(list.nouns, random);
  const suffix = random() < 0.35 ? String(Math.floor(random() * 90) + 10) : '';
  return `${adjective}.${noun}${suffix}`;
}

function pick<T>(items: readonly T[], random: () => number): T {
  const item = items[Math.floor(random() * items.length)];
  if (item === undefined) throw new Error('empty word list');
  return item;
}
